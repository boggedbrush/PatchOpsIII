#!/usr/bin/env python3
"""Regenerate crates/patchops-core/src/pyunicode.rs (Unicode tables Python's str methods use).

    python3 tools/gen_pyunicode.py > crates/patchops-core/src/pyunicode.rs

The tables come from the running interpreter's `unicodedata` (CPython 3.13 = Unicode 15.1.0, the version the legacy
backend ran on): characters `str.isprintable()` rejects (categories Cc Cf Cs Co Cn Zl Zp Zs, except ASCII space) and
the first code point of every run of ten decimal digits (`unicodedata.decimal`, what `int()`/`float()` accept).
"""
import sys
import unicodedata


def runs(pred):
    out, start = [], None
    for i in range(0x110000):
        if pred(i):
            if start is None:
                start = i
            last = i
        elif start is not None:
            out.append((start, last))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


nonprint = runs(lambda i: not chr(i).isprintable() and not 0xD800 <= i <= 0xDFFF)
zeros = []
for i in range(0x110000):
    if unicodedata.decimal(chr(i), None) == 0:
        assert all(unicodedata.decimal(chr(i + k), None) == k for k in range(10))
        zeros.append(i)

w = sys.stdout.write
w("//! Unicode tables for Python string semantics (generated by `tools/gen_pyunicode.py`; do not edit).\n")
w(f"//! Source: CPython {sys.version_info.major}.{sys.version_info.minor} `unicodedata` = Unicode {unicodedata.unidata_version}.\n\n")
w("/// Inclusive code point ranges for which Python's `str.isprintable()` is false (Cc, Cf, Co, Cn, Zl, Zp, Zs\n")
w("/// except U+0020; surrogates cannot occur in a Rust `char`).\n")
w("pub(crate) const NON_PRINTABLE: &[(u32, u32)] = &[\n")
for a, b in nonprint:
    w(f"    (0x{a:x}, 0x{b:x}),\n")
w("];\n\n")
w("/// First code point (digit value 0) of every run of ten decimal digits (`Nd`): what `int()` / `float()` accept as digits.\n")
w("pub(crate) const DECIMAL_ZEROS: &[u32] = &[\n")
for i in range(0, len(zeros), 8):
    w("    " + ", ".join(f"0x{z:x}" for z in zeros[i:i + 8]) + ",\n")
w("];\n")
